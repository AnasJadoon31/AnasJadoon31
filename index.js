// Bind event handlers
function bindEvents() {
  // Preset selector
  elements.templateSelect.addEventListener('change', (e) => {
    loadPreset(e.target.value);
  });
  
  // Reactive updates on form change
  elements.form.addEventListener('input', updateOutput);
  elements.form.addEventListener('change', updateOutput);
  
  // Select checkbox event listeners manually to capture selections
  const checkboxes = document.querySelectorAll('input[name="skills"]');
  checkboxes.forEach(box => {
    box.addEventListener('change', updateOutput);
  });

  // Tab switching
  elements.tabVisual.addEventListener('click', () => switchTab('visual'));
  elements.tabCode.addEventListener('click', () => switchTab('code'));
  elements.tabYaml.addEventListener('click', () => switchTab('yaml'));
  
  // Action buttons
  elements.btnCopy.addEventListener('click', copyToClipboard);
  elements.btnDownload.addEventListener('click', downloadReadme);
}

// Switch between preview tabs
function switchTab(tabName) {
  // Reset all tabs
  elements.tabVisual.classList.remove('active');
  elements.tabVisual.setAttribute('aria-selected', 'false');
  elements.tabCode.classList.remove('active');
  elements.tabCode.setAttribute('aria-selected', 'false');
  elements.tabYaml.classList.remove('active');
  elements.tabYaml.setAttribute('aria-selected', 'false');
  
  elements.contentVisual.classList.remove('active');
  elements.contentCode.classList.remove('active');
  elements.contentYaml.classList.remove('active');
  
  if (tabName === 'visual') {
    elements.tabVisual.classList.add('active');
    elements.tabVisual.setAttribute('aria-selected', 'true');
    elements.contentVisual.classList.add('active');
  } else if (tabName === 'code') {
    elements.tabCode.classList.add('active');
    elements.tabCode.setAttribute('aria-selected', 'true');
    elements.contentCode.classList.add('active');
  } else if (tabName === 'yaml') {
    elements.tabYaml.classList.add('active');
    elements.tabYaml.setAttribute('aria-selected', 'true');
    elements.contentYaml.classList.add('active');
  }
}

