// Generate dynamic GitHub Actions workflow code
function generateYamlWorkflow() {
  const data = getFormData();
  const theme = data.widgetTheme || "github_dark";
  
  let yaml = `name: Update README cards

on:
  schedule:
    - cron: "0 3 * * *" # Runs daily at 3:00 AM UTC
  workflow_dispatch: # Allows manual trigger from Actions tab

permissions:
  contents: write # Grants permission to commit SVGs

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout profile repository
        uses: actions/checkout@v4\n`;

  if (data.cardStats) {
    yaml += `
      - name: Generate stats card
        uses: readme-tools/github-readme-stats-action@v1
        with:
          card: stats
          options: username=\${{ github.repository_owner }}&show_icons=true&theme=${theme}
          path: profile/stats.svg
          token: \${{ secrets.GITHUB_TOKEN }}\n`;
  }

  if (data.cardLangs) {
    yaml += `
      - name: Generate top languages card
        uses: readme-tools/github-readme-stats-action@v1
        with:
          card: langs
          options: username=\${{ github.repository_owner }}&layout=compact&theme=${theme}
          path: profile/langs.svg
          token: \${{ secrets.GITHUB_TOKEN }}\n`;
  }

  yaml += `
      - name: Commit and push generated cards
        run: |
          git config user.name "github-actions[bot]"
          git config user.email "github-actions[bot]@users.noreply.github.com"
          mkdir -p profile
          git add profile/*.svg
          git commit -m "chore: update static README analytics cards [skip ci]" || exit 0
          git push\n`;
          
  return yaml;
}

// Copy markdown content to clipboard
function copyToClipboard() {
  if (!currentMarkdown) return;
  
  navigator.clipboard.writeText(currentMarkdown).then(() => {
    showToast("Copied to clipboard! 📋");
  }).catch(err => {
    console.error('Failed to copy: ', err);
    showToast("Failed to copy. Please copy manually.");
  });
}

// Download markdown file
function downloadReadme() {
  if (!currentMarkdown) return;
  
  const blob = new Blob([currentMarkdown], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'README.md';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  showToast("Downloading README.md... 💾");
}

// Visual Toast notification popup builder
function showToast(message) {
  const existing = document.querySelector('.toast-msg');
  if (existing) {
    existing.remove();
  }
  
  const toast = document.createElement('div');
  toast.className = 'toast-msg';
  toast.textContent = message;
  document.body.appendChild(toast);
  
  setTimeout(() => {
    toast.remove();
  }, 3000);
}

